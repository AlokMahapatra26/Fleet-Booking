/**
 * Static Website Exporter for Fleet-Booking Portals
 * Packages any client portal into a 100% self-contained, pre-rendered,
 * zero-server-dependency ZIP archive that can be hosted anywhere.
 */

const fs = require('fs');
const path = require('path');
const JSZip = require('jszip');
const generator = require('./generator');

const ROOT_DIR = __dirname;

/**
 * Recursively add directory files to a JSZip folder
 * @param {JSZip} zipFolder 
 * @param {string} fsDirPath 
 */
function addDirToZip(zipFolder, fsDirPath) {
  if (!fs.existsSync(fsDirPath)) return;
  const entries = fs.readdirSync(fsDirPath, { withFileTypes: true });

  for (const entry of entries) {
    // Skip hidden files, system files, dev caches
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;

    const fullPath = path.join(fsDirPath, entry.name);
    if (entry.isDirectory()) {
      const subFolder = zipFolder.folder(entry.name);
      addDirToZip(subFolder, fullPath);
    } else if (entry.isFile()) {
      const fileBuffer = fs.readFileSync(fullPath);
      zipFolder.file(entry.name, fileBuffer);
    }
  }
}

/**
 * Generate a customized PWA Web Manifest tailored to client brand
 * @param {object} cfg
 * @returns {string} Formatted JSON string
 */
function generateManifest(cfg) {
  const brandName = (cfg.brand?.name || 'Booking Portal').trim();
  const shortName = (cfg.brand?.shortName || brandName).trim();
  const tagline = (cfg.brand?.tagline || 'Book reliable travel and taxi services').trim();
  const isTravel = cfg.template === 'travel';
  const defaultIcon = isTravel ? 'assets/logo-travel.svg' : 'assets/logo-taxi.svg';
  const logoUrl = (cfg.brand?.logoUrl && !cfg.brand.logoUrl.startsWith('data:')) ? cfg.brand.logoUrl : defaultIcon;
  const primaryColor = cfg.brand?.theme?.primary || (isTravel ? '#0284C7' : '#FFD900');
  const bgColor = cfg.brand?.theme?.background || '#0F172A';

  const manifestObj = {
    id: './',
    name: brandName,
    short_name: shortName,
    description: tagline,
    lang: 'en-IN',
    start_url: './',
    scope: './',
    display: 'standalone',
    display_override: ['standalone', 'minimal-ui'],
    orientation: 'portrait',
    background_color: bgColor,
    theme_color: primaryColor,
    categories: ['travel', 'business'],
    icons: [
      {
        src: logoUrl,
        sizes: '192x192 512x512',
        type: 'image/svg+xml',
        purpose: 'any maskable'
      }
    ],
    shortcuts: [
      {
        name: isTravel ? 'Enquire Tour' : 'Book Taxi Now',
        short_name: isTravel ? 'Tour Inquiry' : 'Book Taxi',
        description: isTravel ? 'Quick travel & tour enquiry' : 'Quick taxi booking form',
        url: './#bookingCard',
        icons: [
          {
            src: logoUrl,
            sizes: '192x192',
            type: 'image/svg+xml'
          }
        ]
      }
    ]
  };

  return JSON.stringify(manifestObj, null, 2);
}

