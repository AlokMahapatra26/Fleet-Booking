/**
 * Build a complete static website ZIP package
 * @param {string} slug - Client slug
 * @param {object} config - Client configuration object
 * @returns {Promise<Buffer>} ZIP file binary buffer
 */
async function buildWebsiteZip(slug, config) {
  if (!slug) slug = 'website';
  if (!config) throw new Error('Missing configuration data for ZIP export');

  const zip = new JSZip();

  // 1. Generate standalone pre-rendered HTML (no server base href)
  const staticHtml = generator.generateStaticHtml(slug, config, { standalone: true });
  zip.file('index.html', staticHtml);

  // 2. Client configuration JSON
  zip.file('config.json', JSON.stringify(config, null, 2));

  // 3. Tailored PWA Manifest
  zip.file('manifest.json', generateManifest(config));

  // 4. GitHub Pages .nojekyll flag
  zip.file('.nojekyll', '');

  // 5. Friendly README with hosting instructions
  zip.file('README.md', generateReadme(slug, config));

  // 6. Master style.css
  const styleCssPath = path.join(ROOT_DIR, 'style.css');
  if (fs.existsSync(styleCssPath)) {
    zip.file('style.css', fs.readFileSync(styleCssPath, 'utf8'));
  }

  // 7. Service Worker
  const swPath = path.join(ROOT_DIR, 'service-worker.js');
  if (fs.existsSync(swPath)) {
    zip.file('service-worker.js', fs.readFileSync(swPath, 'utf8'));
  }

  // 8. CSS Directory (tokens, components, taxi, travel)
  const cssFolder = zip.folder('css');
  const cssFiles = ['tokens.css', 'components.css', 'taxi.css', 'travel.css'];
  cssFiles.forEach(file => {
    const filePath = path.join(ROOT_DIR, 'css', file);
    if (fs.existsSync(filePath)) {
      cssFolder.file(file, fs.readFileSync(filePath, 'utf8'));
    }
  });

  // 9. JS Directory (app.js, taxi.js, travel.js)
  const jsFolder = zip.folder('js');
  const jsFiles = ['app.js', 'taxi.js', 'travel.js'];
  jsFiles.forEach(file => {
    const filePath = path.join(ROOT_DIR, 'js', file);
    if (fs.existsSync(filePath)) {
      jsFolder.file(file, fs.readFileSync(filePath, 'utf8'));
    }
  });

  // 10. Assets Directory (all SVGs, logos, custom logos)
  const assetsFolder = zip.folder('assets');
  const assetsDir = path.join(ROOT_DIR, 'assets');
  addDirToZip(assetsFolder, assetsDir);

  // Generate the ZIP buffer with max compression
  const zipBuffer = await zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 }
  });

  return zipBuffer;
}

module.exports = {
  buildWebsiteZip
};
